"""
siteparts.py - shared writer for the site's split data layer.

Each page loads one small core script (window.UCDATA, UCCTX, TRENDS_DATA, UCDENIED) and
fetches the remaining data in parts, on demand, through ucparts.js at the repository root.
A part is a plain script that registers one value:

    (window.UCPARTS_DATA = window.UCPARTS_DATA || {})["site:campus_0"] = {...};

Inside parts, numeric columns are stored as packed strings: "78,73,,65" is the column
[78, 73, null, 65]. Each number is written with Python's repr (the shortest decimal that
round-trips the double), so JavaScript's +"4.24" reads the same IEEE value JSON would give;
nothing is rounded. An integer-valued float is written without its ".0" (80.0 -> "80"), the
same double either way. ucparts.js unpacks a column with UCPARTS.unpack().
"""
import json
import math
import os


def fmt_num(v):
    """One packed-column cell: '' for None, otherwise the shortest exact decimal."""
    if v is None:
        return ""
    if isinstance(v, bool):
        raise TypeError("booleans do not belong in a packed column")
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        if math.isnan(v) or math.isinf(v):
            raise ValueError("packed columns cannot hold NaN or infinity")
        if v.is_integer() and abs(v) < 1e16:
            return str(int(v))
        return repr(v)
    raise TypeError(f"packed columns hold numbers or None, not {type(v).__name__}")


def pack(values):
    """[78, 73, None, 65] -> '78,73,,65'. A column has at least one cell: '' is [None]."""
    values = list(values)
    if not values:
        raise ValueError("a packed column needs at least one cell (represent an empty series another way)")
    return ",".join(fmt_num(v) for v in values)


def pack_rows(rows, ncols):
    """Row arrays -> list of ncols packed column strings (the transpose)."""
    return [pack([r[i] for r in rows]) for i in range(ncols)]


def unpack(s):
    """The Python mirror of UCPARTS.unpack (used by the build's own checks)."""
    out = []
    for cell in s.split(","):
        if cell == "":
            out.append(None)
        else:
            f = float(cell)
            out.append(int(f) if f.is_integer() and "." not in cell and "e" not in cell else f)
    return out


def _dumps(obj):
    return json.dumps(obj, separators=(",", ":"), ensure_ascii=False, allow_nan=False)


def write_core(path, global_name, obj, generator):
    """The page's core script: window.<global_name> = {...};"""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"/* Auto-generated by {generator} - do not edit by hand. */\n")
        fh.write(f"window.{global_name} = ")
        fh.write(_dumps(obj))
        fh.write(";\n")
    return os.path.getsize(path)


def write_part(path, key, obj, generator):
    """One data part, registered under `key` for ucparts.js."""
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(f"/* Auto-generated by {generator} - do not edit by hand. Data part {key}. */\n")
        fh.write("(window.UCPARTS_DATA=window.UCPARTS_DATA||{})[")
        fh.write(_dumps(key))
        fh.write("]=")
        fh.write(_dumps(obj))
        fh.write(";\n")
    return os.path.getsize(path)


def read_script_json(path):
    """Read back a core script or part: the JSON object after the first '=' of the assignment."""
    import re
    with open(path, encoding="utf-8") as fh:
        s = fh.read()
    m = re.search(r"=\s*\{", s)
    start = m.end() - 1
    end = s.rindex("}") + 1
    return json.loads(s[start:end])
